#!/usr/bin/env python3
"""Cross-platform energy projection for SpikeRPGNN.

Maps the *independently re-derived* measured spike-driven SOP counts
(analysis_v30.json, the same SOP model used by Table 3) onto published
per-event energy constants of real neuromorphic silicon:

  - Loihi   : 23.6 pJ/SOP   (Davies et al., 2018, Nature,
                              "Loihi: A neuromorphic manycore processor
                               with on-chip learning")
  - TrueNorth: 26 pJ/SOP    (Merolla et al., 2014, Science,
                              "A million spiking-neuron integrated circuit";
                              per-event figure consistent with Cassidy et al., 2014)

These are DEVICE-MEASURED constants, in contrast to the analytic 0.9 pJ/SOP
theoretical value (Han et al., 2016) used in Table 3. The SOP counts are
identical; only the per-operation constant changes. This upgrades the
paper's energy claim from "analytic estimate" to "projected on published
silicon constants" -- exactly the "testable on neuromorphic silicon"
statement in the abstract.

Outputs (absolute paths):
  results/energy_silicon_projection.json   -- machine-readable numbers
  manuscript/tables/energy_silicon_table.tex -- \input-able table body
  figures/energy_silicon_projection.pdf     -- grouped-bar figure (log y, IEEE style)
"""
import json, os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager

POST = "D:/2026/paper/PBB/post"
ANALYSIS = f"{POST}/results/analysis_v30.json"
OUT_JSON = f"{POST}/results/energy_silicon_projection.json"
OUT_TAB  = f"{POST}/manuscript/tables/energy_silicon_table.tex"
OUT_FIG  = f"{POST}/figures/energy_silicon_projection.pdf"

# per-operation energy constants (Joule)
E_ANALYTIC = 0.9e-12    # pJ/SOP theoretical (Han16)
E_DENSE    = 4.6e-12    # pJ per dense MAC @45nm (Han16)
E_LOIHI    = 23.6e-12   # pJ/SOP measured (Davies18)
E_TN       = 26.0e-12   # pJ/SOP measured (Merolla14)
UJ = 1e6  # J -> micro-Joule

DS_ORDER = ["MUTAG", "PROTEINS", "ENZYMES"]


def main():
    d = json.load(open(ANALYSIS))
    rows = d["energy"]
    by_method = {r["method"]: r for r in rows}

    proj = {}  # method -> per-ds + mean for each substrate (all in micro-Joule)
    # Correct, constant-preserving relationship: E_new = E_data * (new_const / base_const),
    # because the operation count (SOP or FLOPs) is identical and the 1e6 J->uJ factor cancels.
    # Spiking rows in analysis_v30.json are charged at E_ANALYTIC (0.9 pJ); dense rows at E_DENSE (4.6 pJ).
    for m, r in by_method.items():
        per = r["per_ds"]
        base = E_ANALYTIC if r["type"] == "spiking" else E_DENSE
        # The rate printed next to a three-dataset MEAN energy must be the
        # three-dataset mean rate, not the rate of whichever dataset sorts
        # first. Taking DS_ORDER[0] labelled this whole table with MUTAG's
        # rate (0.41 / 0.43) and contradicted Table 3, which labels the same
        # quantity with the mean rate (0.40 / 0.41).
        _rb = r.get("r_bar_mean")
        if _rb is None and r["type"] == "spiking":
            _rr = [per[d]["r_bar"] for d in DS_ORDER if per.get(d, {}).get("r_bar")]
            _rb = sum(_rr) / len(_rr) if _rr else None
        entry = {"type": r["type"], "r_bar": _rb}
        for tag, e in [("analytic", E_ANALYTIC), ("loihi", E_LOIHI),
                       ("truenorth", E_TN), ("dense_gpu", E_DENSE)]:
            ratio = e / base
            entry[f"E_{tag}"] = {ds: per[ds]["energy_uj"] * ratio for ds in DS_ORDER}
            entry[f"E_{tag}_mean"] = sum(entry[f"E_{tag}"][ds] for ds in DS_ORDER) / 3.0
        proj[m] = entry

    # reference dense (Proto-GIN, r=1.0) on each substrate
    ref = "Proto-GIN"
    ref_loihi = proj[ref]["E_loihi_mean"]
    ref_tn = proj[ref]["E_truenorth_mean"]
    for m, e in proj.items():
        if e["type"] == "spiking":
            e["red_vs_dense_loihi"] = (1 - e["E_loihi_mean"] / ref_loihi) * 100
            e["red_vs_dense_tn"] = (1 - e["E_truenorth_mean"] / ref_tn) * 100

    # ---- JSON ----
    out = {
        "constants_pJ": {"analytic": 0.9, "dense_gpu": 4.6, "loihi": 23.6, "truenorth": 26.0},
        "reference_dense": ref,
        "reference_dense_E_loihi_mean_uj": ref_loihi,
        "reference_dense_E_truenorth_mean_uj": ref_tn,
        "projection": proj,
    }
    json.dump(out, open(OUT_JSON, "w"), indent=2)
    print("wrote", OUT_JSON)

    # ---- LaTeX table snippet ----
    def fmt(x):
        return f"{x:.2f}"
    spiking = [m for m, e in proj.items() if e["type"] == "spiking"]
    lines = []
    lines.append("% Generated by neuromorphic_silicon_projection.py -- do not edit by hand")
    lines.append("% Energy projection onto published neuromorphic-silicon per-event constants")
    lines.append("\\begin{table}[width=.95\\linewidth,cols=7,pos=htbp]")
    lines.append("\\caption{Cross-platform energy projection (\\textmu J per graph, 1-shot, MUTAG/PROTEINS/ENZYMES). The spike-driven SOP counts are the same independently re-derived measurements used in Table~\\ref{tab:energy}; only the per-operation constant changes. Constants: analytic $0.9$~pJ/SOP \\citep{Horowitz14}, dense MAC $4.6$~pJ \\citep{Sun24}, Loihi $23.6$~pJ/SOP \\citep{Davies18}, TrueNorth $26$~pJ/SOP \\citep{Merolla14}.}")
    lines.append("\\label{tab:energy_silicon}")
    lines.append("\\centering \\scriptsize")
    lines.append("\\setlength{\\tabcolsep}{1.5pt}")
    lines.append("\\begin{tabular}{@{} >{\\raggedright\\arraybackslash}p{0.20\\linewidth} c c c c c c @{}}")
    lines.append("\\toprule")
    lines.append("\\textbf{Method} & \\multicolumn{3}{c}{\\textbf{Loihi (23.6 pJ/SOP)}} & \\textbf{Mean} & \\textbf{Mean} & \\textbf{Red.\\textsuperscript{\\textdagger}} \\\\")
    lines.append(" & \\textbf{MUTAG} & \\textbf{PROTEINS} & \\textbf{ENZYMES} & \\textbf{Loihi} & \\textbf{TrueNorth} & \\textbf{(\\%)} \\\\")
    lines.append("\\midrule")
    # dense reference row (r=1.0)
    dr = proj[ref]
    lines.append(f"Dense (r=1.0) ref. & {fmt(dr['E_loihi']['MUTAG'])} & {fmt(dr['E_loihi']['PROTEINS'])} & {fmt(dr['E_loihi']['ENZYMES'])} & {fmt(dr['E_loihi_mean'])} & {fmt(dr['E_truenorth_mean'])} & -- \\\\")
    rbar_txt = ", ".join(f"{m} $\\bar{{r}}={proj[m]['r_bar']:.2f}$"
                         for m in spiking if proj[m]["r_bar"])
    for m in spiking:
        e = proj[m]
        lines.append(f"{m} & {fmt(e['E_loihi']['MUTAG'])} & {fmt(e['E_loihi']['PROTEINS'])} & {fmt(e['E_loihi']['ENZYMES'])} & {fmt(e['E_loihi_mean'])} & {fmt(e['E_truenorth_mean'])} & {e['red_vs_dense_loihi']:.1f} \\\\")
    lines.append("\\bottomrule")
    _note = ("\\multicolumn{7}{p{\\dimexpr\\linewidth-14\\tabcolsep\\relax}}{\\scriptsize \\textsuperscript{\\textdagger}Reduction of the spiking method relative to the dense (r=1.0) reference implemented on the \\emph{same} substrate (Loihi/TrueNorth), i.e., a technology-matched comparison. The dense reference is Proto-GIN. The measured mean firing rates behind the spiking rows are {rbar_txt}. The spiking rows carry the $T=8$ temporal integration factor ($T\\bar{r}\\times\\mathrm{FLOPs}$ events), so they are charged for all eight steps; omitting that factor would report a spurious saving of $58$--$60\\%$. Under the corrected accounting the reduction is \\emph{negative}: the spiking methods overrun the same-substrate dense reference by roughly $218$--$233\\%$, because Loihi/TrueNorth per-operation energy (24--26~pJ) exceeds a 45-nm dense MAC (4.6~pJ) and the $T=8$ event count more than offsets the cheaper per-event price. We report this reversal explicitly rather than quoting the uncorrected figure. What the controllable $\\bar{r}$ provides on this axis is a selectable, reproducible operating point, not a guaranteed saving: cost scales as $T\\bar{r}$, so a substantially lower commanded rate would be needed to reach parity, and whether that is attainable on a given substrate is an empirical question we do not claim to have settled.}")
    lines.append(_note.replace("{rbar_txt}", rbar_txt))
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    open(OUT_TAB, "w").write("\n".join(lines) + "\n")
    print("wrote", OUT_TAB)

    # ---- Figure ----
    # The publication PDF figure is produced by the dependency-free generator
    # code/scripts/make_silicon_figure_pdf.py (hand-written vector PDF), which
    # reads the JSON above. (matplotlib savefig is killed by the sandbox here,
    # so it is intentionally not invoked from this script.)
    print("figure: run code/scripts/make_silicon_figure_pdf.py ->", OUT_FIG)

    # ---- console summary ----
    print("\n=== Cross-platform projection (mean, uJ/graph) ===")
    print(f"{'Method':22s} {'Analytic':>9s} {'Loihi':>9s} {'TrueN':>9s} {'DenseGPU':>9s}")
    for m in ["Proto-GIN", "Spike-GNN (Euc.)", "SpikeRPGNN"]:
        e = proj[m]
        print(f"{m:22s} {e['E_analytic_mean']:9.2f} {e['E_loihi_mean']:9.2f} {e['E_truenorth_mean']:9.2f} {e['E_dense_gpu_mean']:9.2f}")
    print(f"\nSpikeRPGNN reduction vs dense-on-Loihi : {proj['SpikeRPGNN']['red_vs_dense_loihi']:.1f}%")
    print(f"SpikeRPGNN reduction vs dense-on-TrueN  : {proj['SpikeRPGNN']['red_vs_dense_tn']:.1f}%")


if __name__ == "__main__":
    main()
