def fmt(x):
    return "---" if x is None else (f"{x*100:.1f}" if isinstance(x, float) else str(x))


def load():
    """Locate analysis_v30.json.

    Prefer the historical relative location, then fall back to the repository
    layout (<repo>/results/analysis_v30.json) so the generator runs from any
    working directory instead of silently producing empty tables.
    """
    repo_root = os.path.abspath(os.path.join(_SCRIPT_DIR, "..", ".."))
    candidates = [
        os.path.join(os.getcwd(), "spikergnn_results", "analysis_v30.json"),
        os.path.join(repo_root, "results", "analysis_v30.json"),
        os.path.join(repo_root, "spikergnn_results", "analysis_v30.json"),
    ]
    for p in candidates:
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                return json.load(f)
    raise FileNotFoundError(
        "analysis_v30.json not found; looked in: " + ", ".join(candidates))


def render_main_table(d):
    meth = {}
    # collect all available method x ds x shot means/stds/n
    for section, entries in d.items():
        if section in ("spikergnn", "msg", "ann", "euc"):
            for key, v in entries.items():
                if "mean" not in v:
                    continue
                if section == "spikergnn":
                    m, ds, shot = "SpikeRPGNN", *key.rsplit("_", 1)
                    shot = int(shot)
                    ds = ds
                elif section == "msg":
                    m, ds, shot = "MSG*", *key.rsplit("_", 1)
                    shot = int(shot); ds = ds
                elif section == "euc":
                    ds, shot = key.rsplit("_", 1)
                    m, shot = "Spike-GNN (Euc.)", int(shot)
                elif section == "ann":
                    model, ds, shot = key.split("_", 2)
                    shot = int(shot.split("shot")[0])
                    m = f"Proto-{model.upper()}"
                else:
                    continue
                meth.setdefault(m, {}).setdefault((ds, shot), v)

    # Merge hyperbolic GNN baselines (HGCN / H2H) from their own result file.
    # They cover only the three Tier-1 benchmarks (MUTAG/PROTEINS/ENZYMES);
    # DD and R-M5K cells stay '---' because those runs were never executed
    # (heavier hyperbolic message passing was not budgeted on the large graphs).
    _repo_root = os.path.abspath(os.path.join(_SCRIPT_DIR, "..", ".."))
    _hgcn_cands = [
        os.path.join(os.getcwd(), "spikergnn_results", "hgcn_baselines_v30.json"),
        os.path.join(_repo_root, "results", "hgcn_baselines_v30.json"),
        os.path.join(_repo_root, "spikergnn_results", "hgcn_baselines_v30.json"),
    ]
    _hgcn_path = next((x for x in _hgcn_cands if os.path.exists(x)), None)
    if _hgcn_path:
        import re as _re
        _hg = json.load(open(_hgcn_path, encoding="utf-8"))
        _hg_agg = {}
        for _k, _v in _hg.items():
            _m = _re.match(r"^(hgcn|h2h)_(MUTAG|PROTEINS|ENZYMES)_(\d)shot_run(\d+)$", _k)
            if not _m:
                continue
            _pre, _ds, _sh = _m.group(1), _m.group(2), int(_m.group(3))
            _name = "HGCN" if _pre == "hgcn" else "H2H"
            _hg_agg.setdefault((_name, _ds, _sh), []).append(_v["final_acc"])
        for (_name, _ds, _sh), _accs in _hg_agg.items():
            _accs = np.array(_accs, dtype=float)
            meth.setdefault(_name, {})[(_ds, _sh)] = {
                "mean": float(_accs.mean()), "std": float(_accs.std())}

    datasets = ["MUTAG", "PROTEINS", "ENZYMES", "DD", "REDDIT-M5K"]
    lines = ["% Main results table (Table 4)",
             "\\begin{table*}[htbp]",
    # The 10-run claim used to be stated for the whole table, but only
    # SpikeRPGNN actually has 10 runs on DD/R-M5K 1-shot -- every baseline
    # has 5. Printing "10 runs on X" above five rows that have 5 is wrong,
    # so the claim is now scoped to the method that earns it.
             "\\caption{Main Results: Few-Shot Graph Classification Accuracy (mean\\,$\\pm$\\,std \\%, minimum 5 runs per configuration; the five decision-bearing cells --- Tier-1 5-shot and DD/Rdt-M5k 1-shot --- carry 20 runs per arm, and Proto-GAT remains at 5). \\textbf{Bold} indicates the best mean per column. HGCN and H2H are hyperbolic-GNN baselines added for architectural comparison; they were run only on the three Tier-1 benchmarks (MUTAG, PROTEINS, ENZYMES), so their DD and R-M5K entries are omitted.}",
             "\\label{tab:main_results}",
             "\\centering \\scriptsize",
             "\\setlength{\\tabcolsep}{3pt}",
             "\\begin{tabular*}{\\tblwidth}{@{} L *{10}{c} @{}}",
             "\\toprule",
             "\\textbf{Method} & \\multicolumn{2}{c}{MUTAG} & \\multicolumn{2}{c}{PROTEINS} & \\multicolumn{2}{c}{ENZYMES} & \\multicolumn{2}{c}{DD} & \\multicolumn{2}{c}{R-M5K} \\\\",
             "& \\textbf{1-shot} & \\textbf{5-shot} & \\textbf{1-shot} & \\textbf{5-shot} & \\textbf{1-shot} & \\textbf{5-shot} & \\textbf{1-shot} & \\textbf{5-shot} & \\textbf{1-shot} & \\textbf{5-shot} \\\\",
             "\\midrule"]

    # best mean per column (ds, shot) among methods with data -> bold
    best = {}
    for m in ["SpikeRPGNN", "MSG*", "Spike-GNN (Euc.)", "Proto-GIN", "Proto-GCN",
              "Proto-SAGE", "Proto-GAT", "HGCN", "H2H"]:
        for ds in datasets:
            for shot in [1, 5]:
                v = meth.get(m, {}).get((ds, shot))
                if not v:
                    continue
                if (ds, shot) not in best or v["mean"] > best[(ds, shot)]:
                    best[(ds, shot)] = v["mean"]

    for m in ["SpikeRPGNN", "MSG*", "Spike-GNN (Euc.)", "Proto-GIN", "Proto-GCN",
              "Proto-SAGE", "Proto-GAT", "HGCN", "H2H"]:
        cells = []
        for ds in datasets:
            for shot in [1, 5]:
                v = meth.get(m, {}).get((ds, shot))
                if v:
                    txt = f"{v['mean']*100:.1f}$\\pm${v['std']*100:.1f}"
                    if abs(v["mean"] - best.get((ds, shot), -1)) < 1e-9:
                        txt = f"\\textbf{{{txt}}}"
                    cells.append(txt)
                else:
                    cells.append("---")
        lines.append(f"{m} & {' & '.join(cells)} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular*}", "\\end{table*}"])
    return "\n".join(lines)


def render_significance_table(d):
    tests = d.get("significance", [])
    if not tests:
        return "% significance table: no data yet"
    # A cell is Welch only when the two arms genuinely differ in run count;
    # the n>=20 extension makes almost every cell paired, so this must not be
    # inferred from SpikeRPGNN's n alone (that mislabelled all 30 extended
    # paired rows as Welch on 2026-11-10).
    n_welch = sum(1 for t in tests if t.get("n_b", t["n"]) != t["n"])
    welch_txt = (f"{n_welch} cell" + ("s" if n_welch != 1 else "")
                 + " where the arms differ in run count")
    lines = ["% Significance table (Table 6)",
             "\\begin{table*}[htbp]",
             "\\caption{Significance Tests: SpikeRPGNN vs. Baselines "
             "(BH-FDR corrected). Paired $t$-tests where the two arms share a "
             "run count; Welch's $t$-test on the " + welch_txt + ".}",
             "\\label{tab:significance}",
             "\\centering \\scriptsize",
             "\\begin{tabular*}{\\tblwidth}{@{} LLLccccc @{}}",
             "\\toprule",
             "\\textbf{Baseline} & \\textbf{Dataset} & \\textbf{Shot} & $\\Delta$(\\%) & $t$ & $p$ & $q$ & $d$ \\\\",
             "\\midrule"]
    for t in sorted(tests, key=lambda x: (x["dataset"], x["shot"], x["method"])):
        star = "***" if t["q_bh"] < 0.001 else "**" if t["q_bh"] < 0.01 else "*" if t["q_bh"] < 0.05 else "ns"
        lines.append(f"{t['method']} & {t['dataset']} & {t['shot']}-shot & "
                     f"{t['mean_diff']*100:+.1f} & {t['t']:+.2f} & "
                     f"{t['p']:.3f} & {t['q_bh']:.3f} & {t['cohen_d']:+.2f} {star} \\\\")
    _note = ("\\scriptsize $^{*}p<0.05$, $^{**}p<0.01$, $^{***}p<0.001$; "
             "ns: not significant at $q<0.05$. "
             "$d$ is Cohen's $d_{z}$ (mean difference over the SD of those "
             "differences) on the paired cells and standard Cohen's $d$ "
             "(df-weighted pooled SD) on the " + str(n_welch) + " Welch cells. "
             "The capacity-matched grid comprises $60$ cells "
             "(six baselines $\\times$ five datasets $\\times$ two shots) and "
             "all " + str(len(tests)) + " of them are corrected in one BH-FDR "
             "family. After the $n\\geq20$ power extension the only "
             "unequal-count cells are the Proto-GAT rows (SpikeRPGNN $20$ "
             "runs vs Proto-GAT's $5$ on Tier-1 5-shot and DD/Rdt-M5k "
             "1-shot), so those " + str(n_welch) + " cells use Welch's test. "
             "They are retained rather than dropped: excluding "
             "them would shrink the correction family and make every surviving "
             "$q$-value smaller, which is the direction that flatters the "
             "proposed method. Both accuracies of every cell are reported in "
             "Table~\\ref{tab:main_results}.}")
    lines.append("\\bottomrule")
    lines.append("\\multicolumn{8}{p{\\dimexpr\\tblwidth-6\\tabcolsep\\relax}}{" + _note)
    lines.append("\\end{tabular*}")
    lines.append("\\end{table*}")
    return "\n".join(lines)


def render_energy_table(d):
    rows = d.get("energy", [])
    rows5 = d.get("energy_5shot", [])
    common = d.get("energy_common_datasets", ["MUTAG", "PROTEINS", "ENZYMES"])
    if not rows:
        return "% energy table: no data yet"
    nds = len(common)
    m5 = {e["method"]: e for e in rows5}  # 5-shot block, keyed by method
    ncols = nds + 4                       # Method + Shot + ds... + Mean + Red.%
    lines = ["% Energy table (Table 3) -- generated from real measured data only",
             "\\begin{table}[width=.9\\linewidth,cols=%d,pos=htbp]" % ncols,
             "\\caption{Theoretical energy per graph (analytic SOP model, 1-shot and "
             "5-shot, $\\mu$J/graph, " + "/".join(common) + "). Values are deterministic "
             "analytic estimates (no run-to-run error bars), not device measurements; "
             "the model is defined in the footnote.}",
             "\\label{tab:energy}",
             "\\centering \\scriptsize",
             "\\setlength{\\tabcolsep}{2pt}",
             "\\begin{tabular}{@{} >{\\raggedright\\arraybackslash}p{0.22\\linewidth} "
             + " ".join(["c"] * (ncols - 1))
             + " @{}}",
             "\\toprule",
             "\\textbf{Method} & \\textbf{Shot} & "
             + " & ".join(f"\\textbf{{{ds}}}" for ds in common)
             + " & \\textbf{Mean} & \\textbf{Red.}\\% \\\\",
             "\\midrule"]

    def _grp_cells(e):
        cells = []
        for ds in common:
            v = e.get("per_ds", {}).get(ds)
            cells.append(f"{v['energy_uj']:.2f}" if v else "---")
        cells.append(f"{e['energy_uj_mean']:.2f}" if "energy_uj_mean" in e else "---")
        red = e.get("reduction_pct")
        cells.append(f"{red:.1f}\\%" if red is not None else "---")
        return cells

    for e in rows:
        name = e["method"]
        if e.get("r_bar_mean") is not None:
            name += f" ($\\bar{{r}}$={e['r_bar_mean']:.2f})"
        lines.append(name + " & 1-shot & " + " & ".join(_grp_cells(e)) + " \\\\")
        e5 = m5.get(e["method"])
        if e5:
            name5 = e5["method"]
            if e5.get("r_bar_mean") is not None:
                name5 += f" ($\\bar{{r}}$={e5['r_bar_mean']:.2f})"
            lines.append(name5 + " & 5-shot & " + " & ".join(_grp_cells(e5)) + " \\\\")
        else:
            lines.append(e["method"] + " & 5-shot & " + " & ".join(["---"] * (nds + 2)) + " \\\\")
    lines.extend(["\\bottomrule",
                  "\\multicolumn{%d}{p{\\dimexpr\\linewidth-2\\tabcolsep\\relax}}{" % ncols
                  + "\\scriptsize Energy $E=\\mathrm{SOP}\\times e$ with $e_{FLOP}=4.6$ pJ (dense) and "
                  "$e_{SOP}=0.9$ pJ \\citep{Horowitz14}. A spiking model emits $\\bar{r}\\times\\mathrm{FLOPs}$ "
                  "synaptic events on each of its $T=8$ integration steps, so its count is "
                  "$\\mathrm{SOP}_{spiking}=T\\times\\bar{r}\\times\\mathrm{FLOPs}_{dense}$ with the "
                  "measured firing rate $\\bar{r}$; a dense baseline performs a single forward pass and "
                  "carries no $T$ factor. Including $T$ is required for the comparison to be "
                  "like-for-like, and it reduces the advantage over the dense reference from a naive "
                  "$1-\\bar{r}\\,e_{SOP}/e_{FLOP}$ to the values reported here. "
                  "FLOPs are analytic per-architecture counts. Reductions are relative to the "
                  "capacity- and backbone-matched dense Proto-GIN at the same shot. "
                  "The 5-shot spiking cells are priced at the measured 5-shot firing rate "
                  "$\\bar{r}$ printed in their row label; a dense per-graph forward pass carries no "
                  "firing-rate or $T$ factor, so its 1-shot and 5-shot entries coincide. "
                  "Per-operation constants are literature values, not device measurements; the "
                  "independent event-count re-derivation is detailed in Section~\\ref{sec:energy}.}",
                  "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines)


def render_sweep_table(d):
    sw = d.get("sweep", {})
    if not sw:
        return "% lambda sweep table: no data yet"
    lines = ["% Lambda sweep table (Table 8)",
             "\\begin{table*}[htbp]",
             "\\caption{Spike-Rate Regularization Scan ($r^{*}=0.4$, sweep protocol)}",
             "\\label{tab:lambda_sweep}",
             "\\centering \\scriptsize",
             "\\begin{tabular*}{\\tblwidth}{@{} c *{9}{c} @{}}",
             "\\toprule",
             "\\multirow{2}{*}{$\\lambda_{sr}$} & \\multicolumn{3}{c}{MUTAG} & \\multicolumn{3}{c}{PROTEINS} & \\multicolumn{3}{c}{ENZYMES} \\\\",
             "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7} \\cmidrule(lr){8-10}",
             "& Acc(\\%) & $\\bar{r}$ & $E$($\\mu$J) & Acc(\\%) & $\\bar{r}$ & $E$($\\mu$J) & Acc(\\%) & $\\bar{r}$ & $E$($\\mu$J) \\\\",
             "\\midrule"]
    datasets = ["MUTAG", "PROTEINS", "ENZYMES"]
    lambdas = sorted(set(k.split("_")[0] for k in sw))
    for lam_str in lambdas:
        lam = float(lam_str)
        cells = [lam_str]
        for ds in datasets:
            key = f"{lam_str}_{ds}_1"
            v = sw.get(key)
            if v:
                cells.append(f"{v['acc_mean']*100:.1f}")
                cells.append(f"{v['r_bar_mean']:.3f}" if v['r_bar_mean'] is not None else "---")
                # energy: per-dataset analytic SOP model at the measured firing rate
                e = energy_uj(dense_flops("spikergnn", ds), v['r_bar_mean'] if v['r_bar_mean'] is not None else 0.35)
                cells.append(f"{e:.2f}")
            else:
                cells.extend(["---", "---", "---"])
        lines.append(" & ".join(cells) + " \\\\")
    # in-band count over the main matrix's 1-shot cells (the rate discipline
    # evidence quoted by the abstract and introduction)
    _all_rates = [r for _ds in ("MUTAG", "PROTEINS", "ENZYMES", "DD", "REDDIT-M5K")
                  for r in d.get("spikergnn", {}).get(f"{_ds}_1", {}).get("spike_rates", [])]
    _in_band = sum(1 for _r in _all_rates if 0.3 <= _r <= 0.5)
    lines.extend(["\\bottomrule",
                  "\\multicolumn{10}{p{\\dimexpr\\tblwidth-6\\tabcolsep\\relax}}{"
                  "\\scriptsize Sweep protocol: 30 epochs$\\times$10 ep/epoch$\\times$20 test eps, 5 runs. "
                  "$\\lambda=0$ is the no-$\\mathcal{L}_{sr}$ anchor. Energy computed with the analytic SOP model. "
                  f"Across the {_in_band} of {len(_all_rates)} one-shot runs of the main matrix that this "
                  "regularizer serves, the realized rate lands inside the target "
                  "band $[0.3,0.5]$.}",
                  "\\end{tabular*}", "\\end{table*}"])
    return "\n".join(lines)


# Per-dataset ablation metadata. The number of ways and the label differ by
# dataset; the caption used to hard-code "5-way", which leaked an ENZYMES
# template value into the PROTEINS table (2-way), and a single "_proteins"
# suffix for every non-ENZYMES dataset would collide once MUTAG is emitted.
ABLATION_SPECS = {
    "MUTAG":    {"n_way": 2, "label": "tab:ablation_mutag"},
    "PROTEINS": {"n_way": 2, "label": "tab:ablation_proteins"},
    "ENZYMES":  {"n_way": 5, "label": "tab:ablation"},
}


def render_ablation_table(ds, caption_ds):
    """Ablation on `ds` from ablation_50ep_v30.json (real runs, 50 epochs x 5 runs)."""
    import numpy as np, re
    from scipy import stats as st
    repo_root = os.path.abspath(os.path.join(_SCRIPT_DIR, "..", ".."))
    cands = [
        os.path.join(os.getcwd(), "spikergnn_results", "ablation_50ep_v30.json"),
        os.path.join(repo_root, "results", "ablation_50ep_v30.json"),
        os.path.join(repo_root, "spikergnn_results", "ablation_50ep_v30.json"),
    ]
    p = next((x for x in cands if os.path.exists(x)), None)
    if p is None:
        return "% ablation table: no data"
    d = json.load(open(p, encoding="utf-8"))
    KEY_RE = re.compile(
        r"^(full|no_spikes|euclidean|no_frechet|no_dvm|no_meta|no_stmp)"
        r"_(MUTAG|PROTEINS|ENZYMES)_(\d+)shot_run(\d+)$")
    order = [("full", "Full SpikeRPGNN"), ("no_spikes", "w/o Spikes"),
             ("no_stmp", "w/o STMP"),
             ("euclidean", "w/o Riem.\\ (Euc.)"), ("no_frechet", "w/o Fr\\'echet"),
             ("no_dvm", "w/o DvM"), ("no_meta", "w/o Meta")]
    accs = {}
    for k, v in d.items():
        m = KEY_RE.match(k)
        if not m:
            continue
        var, dsv, shot, run = m.group(1), m.group(2), int(m.group(3)), int(m.group(4))
        if dsv != ds or shot != 1:
            continue
        accs.setdefault(var, []).append(v["final_acc"])
    if "full" not in accs:
        return "% ablation table: no full variant"
    base = np.array(accs["full"])
    n = len(base)
    # measured mean firing rate of the full architecture on `ds` 1-shot (v24 main protocol)
    r_full = None
    v24p = "spikergnn_results/full_results_v24.json"
    if os.path.exists(v24p):
        v24 = json.load(open(v24p))
        srs = [vv["final_spike_rate"] for kk, vv in v24.items()
               if isinstance(vv, dict) and vv.get("dataset") == ds
               and vv.get("shot") == 1 and vv.get("final_spike_rate") is not None]
        if srs:
            r_full = float(np.mean(srs))
    spec = ABLATION_SPECS[ds]
    lines = [f"% Ablation table ({ds}, real data, 50ep re-run)",
             "\\begin{table}[width=.9\\linewidth,cols=5,pos=htbp]",
             "\\caption{Ablation Study on %s (%d-way 1-shot, %d runs per variant, "
             "paired $t$-tests vs.\\ Full)}" % (caption_ds, spec["n_way"], n),
             "\\label{%s}" % spec["label"],
             "\\centering \\scriptsize",
             "\\begin{tabular}{@{} l c c c c @{}}",
             "\\toprule",
             "\\textbf{Config.} & \\textbf{Acc.\\ (\\%)} & \\textbf{$E$ ($\\mu$J/g)$^\\dagger$} "
             "& \\textbf{$\\Delta$Acc} & \\textbf{$p$-val} \\\\",
             "\\midrule"]
    for key, label in order:
        if key not in accs:
            continue
        a = np.array(accs[key])
        acc_txt = f"{a.mean()*100:.1f}$\\pm${a.std()*100:.1f}"
        # analytic energy: only where a defensible firing-rate measurement exists
        if key == "full" and r_full is not None:
            e_txt = f"{energy_uj(dense_flops('spikergnn', ds), r_full):.2f}"
        elif key == "no_spikes":
            e_txt = f"{energy_uj(dense_flops('gin', ds)):.2f}"
        else:
            e_txt = "---"
        if key == "full":
            delta, p_txt = "---", "---"
        elif np.allclose(a, base):
            # 1-shot: Fréchet mean of a single point equals the point itself,
            # so the variant is mathematically identical to Full
            delta = f"{(a.mean()-base.mean())*100:+.1f}\\%"
            p_txt = "---"
        else:
            pv = float(st.ttest_rel(base, a).pvalue)
            delta = f"{(a.mean()-base.mean())*100:+.1f}\\%"
            p_txt = f"{pv:.3f}"
        lines.append(f"{label} & {acc_txt} & {e_txt} & {delta} & {p_txt} \\\\")
    note = ("\\scriptsize $^\\dagger$ Analytic SOP model (\\S\\ref{sec:energy}); $E$ is "
            "reported only where the firing rate was reliably measured: Full uses the "
            "measured $\\bar{r}$ of the main %s 1-shot runs (the value reported in "
            "Table~\\ref{tab:energy}), and w/o Spikes is charged at the dense GIN FLOP cost. "
            "Firing rates of the remaining spiking variants were not isolated from the "
            "support-set spike accumulation, so they are not assigned energy values. "
            "w/o STMP removes the spiking temporal message-passing loop altogether (a "
            "single non-spiking RGC pass plus pooling), so it emits no spikes and is not "
            "on the same event-driven accounting; it is therefore also left unvalued. "
            "All seven variants in this table share the unified 50-epoch episodic protocol of "
            "Section~\\ref{sec:setup} with 5 runs per configuration, and the Full row is the "
            "ablation's own 50-epoch, 5-run SpikeRPGNN, so every $\\Delta$ and $p$-value is "
            "computed within a single controlled study (the 1-shot no-op of w/o Fr\\'echet "
            "requires this internal comparison). The Full mean is statistically "
            "indistinguishable from the main-results-table SpikeRPGNN "
            "(Table~\\ref{tab:main_results}); the ${\\sim}1$ percentage-point gap is "
            "run-to-run variance at a matched protocol, not a protocol change. "
            "w/o Fr\\'echet is identical to Full in the 1-shot setting: the "
            "Fr\\'echet mean of a single support point is the point itself.") % ds
    lines.extend(["\\bottomrule",
                  "\\multicolumn{5}{p{\\dimexpr\\linewidth-2\\tabcolsep\\relax}}{" + note + "}",
                  "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines)


